#!/usr/bin/env python3
"""CLI presentation using the synthetic Monte Carlo dataset.

This script is for presentation only. It selects a synthetic product that
produces a feasible range with an SRP reference and prints the five scenarios.
"""

from __future__ import annotations

import pandas as pd

from engine import PivotEngine
from monte_carlo_data import load_synthetic


def main() -> None:
    df = load_synthetic()
    engine = PivotEngine()

    chosen = None
    chosen_result = None
    for _, row in df.iterrows():
        result = engine.calculate(
            materials=float(row["materials"]),
            labor=float(row["labor"]),
            variable_overhead=float(row["variable_overhead"]),
            packaging=float(row["packaging"]),
            freight_in=float(row["freight_in"]),
            fixed_cost_month=float(row["fixed_cost_month"]),
            expected_units=float(row["expected_units"]),
            current_price=float(row["current_price"]),
            target_margin=float(row["target_margin"]),
            markup=float(row["markup"]),
            competitor_low=None if pd.isna(row["competitor_low"]) else float(row["competitor_low"]),
            competitor_high=None if pd.isna(row["competitor_high"]) else float(row["competitor_high"]),
            srp_reference=None if pd.isna(row["srp_reference"]) else float(row["srp_reference"]),
            srp_binding=bool(row["srp_binding"]),
            srp_scenario_name="SRP reference (synthetic)",
            srp_label="Synthetic SRP reference generated by Monte Carlo; not a DTI bulletin",
        )
        if result.range_state == "feasible" and result.srp_reference is not None:
            chosen = row
            chosen_result = result
            break

    if chosen is None or chosen_result is None:
        raise SystemExit("No feasible synthetic product with an SRP reference was found.")

    print("=" * 78)
    print("SMARTPRICING PRESENTATION — SYNTHETIC MONTE CARLO DATA")
    print("=" * 78)
    print("NOT REAL MSE DATA. For presentation and software testing only.")
    print()
    print(f"Product:      {chosen['product_id']} — {chosen['product_name']}")
    print(f"Subsector:    {chosen['subsector']}")
    print(f"Range state:  {chosen_result.range_state}")
    print()
    print("Five reference scenarios")
    for scenario in chosen_result.scenarios:
        print(f"  {scenario.name:28s} {scenario.value:18s} {scenario.status}")
    print()
    print(
        f"Reference range: ₱{chosen_result.range_low:,.2f} – "
        f"₱{chosen_result.range_high:,.2f}"
    )
    print()
    print("The table is a reference comparison, not a price recommendation.")
    print("The owner makes the final pricing decision.")


if __name__ == "__main__":
    main()
